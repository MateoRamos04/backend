CREATE TABLE Genre
(
    GenreId INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    Name NVARCHAR(120),
    CONSTRAINT PK_Genre PRIMARY KEY (GenreId)
);

CREATE TABLE MediaType
(
    MediaTypeId INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    Name NVARCHAR(120),
    CONSTRAINT PK_MediaType PRIMARY KEY (MediaTypeId)
);

CREATE TABLE Artist
(
    ArtistId INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    Name NVARCHAR(120),
    CONSTRAINT PK_Artist PRIMARY KEY (ArtistId)
);

CREATE TABLE Album
(
    AlbumId INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    Title NVARCHAR(160) NOT NULL,
    ArtistId INTEGER NOT NULL,
    CONSTRAINT PK_Album PRIMARY KEY (AlbumId)
);

CREATE TABLE Track
(
    TrackId INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    Name NVARCHAR(200) NOT NULL,
    AlbumId INTEGER,
    MediaTypeId INTEGER NOT NULL,
    GenreId INTEGER,
    Composer NVARCHAR(220),
    Milliseconds INTEGER NOT NULL,
    Bytes INTEGER,
    UnitPrice NUMERIC(10,2) NOT NULL,
    CONSTRAINT PK_Track PRIMARY KEY (TrackId)
);

CREATE TABLE Employee
(
    EmployeeId INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    LastName NVARCHAR(20) NOT NULL,
    FirstName NVARCHAR(20) NOT NULL,
    Title NVARCHAR(30),
    ReportsTo INTEGER,
    BirthDate TIMESTAMP,
    HireDate TIMESTAMP,
    Address NVARCHAR(70),
    City NVARCHAR(40),
    State NVARCHAR(40),
    Country NVARCHAR(40),
    PostalCode NVARCHAR(10),
    Phone NVARCHAR(24),
    Fax NVARCHAR(24),
    Email NVARCHAR(60),
    CONSTRAINT PK_Employee PRIMARY KEY (EmployeeId)
);

CREATE TABLE Customer
(
    CustomerId INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    FirstName NVARCHAR(40) NOT NULL,
    LastName NVARCHAR(20) NOT NULL,
    Company NVARCHAR(80),
    Address NVARCHAR(70),
    City NVARCHAR(40),
    State NVARCHAR(40),
    Country NVARCHAR(40),
    PostalCode NVARCHAR(10),
    Phone NVARCHAR(24),
    Fax NVARCHAR(24),
    Email NVARCHAR(60) NOT NULL,
    SupportRepId INTEGER,
    CONSTRAINT PK_Customer PRIMARY KEY (CustomerId)
);

CREATE TABLE Invoice
(
    InvoiceId INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    CustomerId INTEGER NOT NULL,
    InvoiceDate TIMESTAMP NOT NULL,
    BillingAddress NVARCHAR(70),
    BillingCity NVARCHAR(40),
    BillingState NVARCHAR(40),
    BillingCountry NVARCHAR(40),
    BillingPostalCode NVARCHAR(10),
    Total NUMERIC(10,2) NOT NULL,
    CONSTRAINT PK_Invoice PRIMARY KEY (InvoiceId)
);

CREATE TABLE InvoiceLine
(
    InvoiceLineId INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    InvoiceId INTEGER NOT NULL,
    TrackId INTEGER NOT NULL,
    UnitPrice NUMERIC(10,2) NOT NULL,
    Quantity INTEGER NOT NULL,
    CONSTRAINT PK_InvoiceLine PRIMARY KEY (InvoiceLineId)
);

CREATE TABLE Playlist
(
    PlaylistId INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    Name NVARCHAR(120),
    CONSTRAINT PK_Playlist PRIMARY KEY (PlaylistId)
);

CREATE TABLE PlaylistTrack
(
    PlaylistId INTEGER NOT NULL,
    TrackId INTEGER NOT NULL,
    CONSTRAINT PK_PlaylistTrack PRIMARY KEY (PlaylistId, TrackId)
);
